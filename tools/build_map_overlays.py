"""Build complete zone artwork metadata from the Forever client's DB2 tables.

    python tools/build_map_overlays.py [1.60.1.70170]

The client only returns discovered overlays through its Lua API. WorldMapOverlay
and WorldMapOverlayTile describe all artwork, including undiscovered regions.
Source CSVs are exported from the client build by wago.tools and cached locally.
Only metadata and FileDataIDs are distributed; textures stay in the game client.
"""
import csv
import io
from pathlib import Path
import sys
import urllib.request

HERE = Path(__file__).resolve().parent
BUILD = "1.60.1.70170"


def fetch(table, build):
    path = HERE / ".cache" / f"{table}-{build}.csv"
    if not path.exists():
        path.parent.mkdir(exist_ok=True)
        request = urllib.request.Request(
            f"https://wago.tools/db2/{table}/csv?build={build}",
            headers={"User-Agent": "Wayfinder-map-overlay-builder"},
        )
        with urllib.request.urlopen(request, timeout=45) as response:
            path.write_bytes(response.read())
    return list(csv.DictReader(io.StringIO(path.read_text(encoding="utf-8-sig"))))


def build(overlays, tiles, version):
    files = {}
    for tile in tiles:
        if int(tile["LayerIndex"]) != 0:
            continue
        key = int(tile["RowIndex"]), int(tile["ColIndex"])
        files.setdefault(int(tile["WorldMapOverlayID"]), {})[key] = int(tile["FileDataID"])
    maps = {}
    for record in sorted(overlays, key=lambda r: int(r["ID"])):
        if int(record["PlayerConditionID"]) != 0:
            continue
        art = int(record["UiMapArtID"])
        width, height = int(record["TextureWidth"]), int(record["TextureHeight"])
        if art <= 0 or width <= 0 or height <= 0:
            continue
        columns, rows = (width+255)//256, (height+255)//256
        record_files = files.get(int(record["ID"]), {})
        # Some builds retain obsolete overlay records without any artwork tiles.
        if not record_files:
            continue
        expected = [(row, col) for row in range(rows) for col in range(columns)]
        if any(not record_files.get(key) for key in expected):
            raise ValueError(f"overlay {record['ID']} has incomplete texture tiles")
        maps.setdefault(art, []).append([
            width, height, int(record["OffsetX"]), int(record["OffsetY"]),
            *(record_files[key] for key in expected),
        ])
    lines = [
        "-- GENERATED by tools/build_map_overlays.py from client DB2 records.",
        f"-- Client build: {version}. Textures remain Blizzard's game assets.",
        "-- [uiMapArtID] = { {width, height, offsetX, offsetY, fileDataIDs...}, ... }",
        "local _, ns = ...", "", f'ns.MapOverlayDataBuild = "{version}"',
        "ns.MapOverlayData = {",
    ]
    for art, records in sorted(maps.items()):
        lines.append(f"\t[{art}] = {{")
        for record in records:
            lines.append("\t\t{" + ",".join(map(str, record)) + "},")
        lines.append("\t},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    version = sys.argv[1] if len(sys.argv) > 1 else BUILD
    result = build(fetch("WorldMapOverlay", version), fetch("WorldMapOverlayTile", version), version)
    target = HERE.parent / "Wayfinder/Data/MapOverlays.lua"
    target.write_text(result, encoding="utf-8", newline="\n")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
